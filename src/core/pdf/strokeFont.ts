const ADVANCE = 1.32
const SPACE = 0.7

export interface StrokeText {
  polylines: number[][][]
  width: number
}

/**
 * Lay out a string as polylines. `size` is cap height in millimetres; the
 * result is in the same millimetre space as the die line, y measured DOWN to
 * match the SVG convention the generators use.
 */
export function strokeText(text: string, x: number, y: number, size: number, anchor: 'start' | 'middle' | 'end' = 'start'): StrokeText {
  const chars = [...text.toUpperCase()]
  let advance = 0
  for (const ch of chars) advance += ch === ' ' ? SPACE * size : ADVANCE * size
  if (chars.length) advance -= (ADVANCE - 1) * size

  const startX = anchor === 'start' ? x : anchor === 'middle' ? x - advance / 2 : x - advance
  const polylines: number[][][] = []
  let cx = startX

  for (const ch of chars) {
    if (ch === ' ') {
      cx += SPACE * size
      continue
    }
    const g = G[ch]
    if (g) {
      for (const stroke of g) {
        polylines.push(stroke.map(([gx, gy]) => [cx + gx * size, y - gy * size]))
      }
    }
    cx += ADVANCE * size
  }

  return { polylines, width: advance }
}
